const DICTIONNAIRES: Record<string, Dictionnaire> = { fr, en, es, de, it, pt, zh, ja, ko, ar }

/** Le texte d'interface dans la langue voulue (l'anglais, puis le français, à défaut), variables remplacées. */
export function ui(langue: string, cle: CleUi, vars?: Record<string, string | number>): string {
  const brut = DICTIONNAIRES[langue]?.[cle] ?? DICTIONNAIRES.en[cle] ?? fr[cle]
  return vars ? brut.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? '')) : brut
}

/** Tout le dictionnaire d'une langue, pour le passer à un composant du navigateur. */
export function dictionnaire(langue: string): Dictionnaire {
  return DICTIONNAIRES[langue] ?? DICTIONNAIRES.en
}

export type DictionnaireUi = Dictionnaire

/** Remplace {variables} dans un texte déjà choisi (côté navigateur). */
export const remplir = (t: string, vars: Record<string, string | number>) => t.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ''))

/** Étiquette BCP 47 pour les formats de nombres, de prix et d'heures. */
export function locale(langue: string): string {
  return (
    { fr: 'fr-CA', en: 'en-CA', es: 'es-ES', de: 'de-DE', it: 'it-IT', pt: 'pt-PT', zh: 'zh-CN', ja: 'ja-JP', ko: 'ko-KR', ar: 'ar-u-nu-latn' } as Record<string, string>
  )[langue] ?? 'en-CA'
}

// ---------------------------------------------------------------------------
// Formats : prix, heures
// ---------------------------------------------------------------------------

export function formaterPrix(montant: number, devise: string, langue: string): string {
  try {
    return new Intl.NumberFormat(locale(langue), { style: 'currency', currency: devise || 'CAD', minimumFractionDigits: Number.isInteger(montant) ? 0 : 2 }).format(montant)
  } catch {
    return `${montant.toFixed(2)} $`
  }
}

/** « 11:30 » → « 11 h 30 » en français, « 11:30 AM » en anglais, etc. */
export function formaterHeure(hhmm: string, langue: string): string {
  const [h, m] = hhmm.split(':').map(Number)
  if (langue === 'fr') return m ? `${h} h ${String(m).padStart(2, '0')}` : `${h} h`
  const d = new Date(Date.UTC(2026, 0, 1, h, m))
  return new Intl.DateTimeFormat(locale(langue), { hour: 'numeric', minute: '2-digit', timeZone: 'UTC' }).format(d)
}

