export const TEXTES_PORTAIL: Record<LanguePortail, Textes> = { fr, en }

/** « 2 min 13 s », « 45 s », « 1 h 05 » / « 2m 13s »… */
export function duree(sec: number, l: LanguePortail): string {
  const s = Math.max(0, Math.round(sec))
  if (s < 60) return `${s} s`
  const m = Math.floor(s / 60)
  if (m < 60) return l === 'fr' ? `${m} min${s % 60 ? ` ${String(s % 60).padStart(2, '0')} s` : ''}` : `${m}m ${String(s % 60).padStart(2, '0')}s`
  const h = Math.floor(m / 60)
  return l === 'fr' ? `${h} h ${String(m % 60).padStart(2, '0')}` : `${h}h ${String(m % 60).padStart(2, '0')}m`
}
